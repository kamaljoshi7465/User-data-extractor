router = APIRouter(prefix="/api/users", tags=["Database"])

# ----------------------------------------------------------------------
# Create tables automatically when the FastAPI app starts.
# ----------------------------------------------------------------------
@router.on_event("startup")
async def create_tables():
    async with engine.begin() as conn:
        await conn.run_sync(Base.metadata.create_all)


# ----------------------------------------------------------------------
# POST /api/users/bulk-insert
# Accept a CSV file (the one produced by the extractor) and insert all rows.
# ----------------------------------------------------------------------
@router.post(
    "/bulk-insert",
    status_code=status.HTTP_201_CREATED,
    summary="Insert all ARRT records from a CSV file",
    description=(
        "Upload the CSV generated by the extractor (`exports/*.csv`). "
        "Each row is parsed and inserted into the `arrt_users` table. "
        "Duplicate `detail_token` values are ignored (`ON CONFLICT DO NOTHING`)."
    ),
)
async def bulk_insert_csv(
    file: UploadFile = File(..., description="CSV file produced by the extractor"),
    db: AsyncSession = Depends(get_db),
):
    # ---- Read the uploaded CSV file -----------------------------------
    import codecs
    content = await file.read()
    # Decode with utf‑8‑sig to strip a possible BOM automatically
    csv_text = codecs.decode(content, "utf-8-sig")
    csv_stream = io.StringIO(csv_text)

    reader = csv.DictReader(csv_stream)
    rows_to_insert: List[Dict[str, Any]] = []

    for row in reader:
        rows_to_insert.append({
            "name": row.get("name") or row.get("Name"),
            "city": row.get("city") or row.get("City"),
            "state": row.get("state") or row.get("State"),
            "credential_string": (
                row.get("credential_string")
                or row.get("Credential String")
                or row.get("credentialString")
            ),
            "detail_token": (
                row.get("detail_token")
                or row.get("Detail Token")
                or row.get("detailtoken")
                or row.get("token")
            ),
            "raw_json": row,
        })

    if not rows_to_insert:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="CSV contains no data rows.",
        )

    # ---- Batch INSERT (keep existing batch logic) ----------------------
    BATCH_SIZE = 4000  # safe margin (<32767 parameters)
    total_inserted = 0
    for start in range(0, len(rows_to_insert), BATCH_SIZE):
        batch = rows_to_insert[start : start + BATCH_SIZE]
        stmt = insert(ArrtUser).values(batch).on_conflict_do_nothing(
            index_elements=["detail_token"]
        )
        try:
            async with db.begin():
                await db.execute(stmt)
                total_inserted += len(batch)
        except Exception as exc:
            raise HTTPException(
                status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
                detail=f"Database error during batch insert: {exc}",
            )

    return {
        "inserted": total_inserted,
        "message": "All rows processed – duplicates (if any) were ignored.",
    }



@router.get(
    "/all",
    response_model=List[Dict[str, Any]],
    status_code=status.HTTP_200_OK,
    summary="Fetch ARRT users with pagination",
)
async def get_all_users(
    skip: int = Query(0, ge=0),
    limit: int = Query(100, ge=1, le=1000),
    search: str | None = Query(None),
    db: AsyncSession = Depends(get_db),
):
    stmt = select(ArrtUser)

    # Search by name (case-insensitive)
    if search and search.strip():
        search_term = search.strip()
        stmt = stmt.where(
            ArrtUser.name.ilike(f"%{search_term}%")
        )

    # Stable ordering + pagination
    stmt = stmt.order_by(ArrtUser.id).offset(skip).limit(limit)

    result = await db.execute(stmt)
    users = result.scalars().all()

    return [
        {
            "id": u.id,
            "name": u.name,
            "city": u.city,
            "state": u.state,
            "credential_string": u.credential_string,
            "detail_token": u.detail_token,
            "raw_json": u.raw_json,
            "fetched_at": u.fetched_at.isoformat() if u.fetched_at else None,
        }
        for u in users
    ]


